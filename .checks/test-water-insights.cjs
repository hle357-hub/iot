const assert = require('assert/strict');
const C = require('D:/iot/sites/thuy-trac/dist/control-core.js');
const base = C.defaults();
assert.equal(C.validate({ ...base, intervalMs: 1000, reportIntervalMs: 10000 }).reportIntervalMs, 10000);
assert.throws(() => C.validate({ ...base, intervalMs: 10000, reportIntervalMs: 1000 }), /lớn hơn hoặc bằng/);
assert.throws(() => C.validate({ ...base, sensorHeightCm: -1 }));
assert.throws(() => C.validate({ ...base, sensorHeightCm: 600.01 }));
assert.throws(() => C.validate({ ...base, sensorHeightCm: 2.001 }));
const legacy = { ...base, intervalMs: 10000 }; delete legacy.reportIntervalMs; delete legacy.sensorHeightCm;
assert.equal(C.validate(legacy).reportIntervalMs, 10000);
assert.equal(C.validate(legacy).sensorHeightCm, 0);
assert.equal(C.heightFor(25.3, 100).value, 74.7);
assert.equal(C.heightFor(101, 100).reason, 'out-of-range');
assert.equal(C.heightFor(0, 100).reason, 'invalid');
assert.equal(C.heightFor(20, 0).reason, 'uncalibrated');
assert.equal(C.heightFor(100, 100).value, 0);
assert(C.commandsFor({ ...base, sensorHeightCm: 100, reportIntervalMs: 10000 }).includes('HEIGHT 10000'));
assert(C.commandsFor({ ...base, reportIntervalMs: 10000 }).includes('REPORT 10000'));
const sample = (sec, average) => ({ rtc: `12:00:${String(sec).padStart(2, '0')} 30/10/2026`, average });
const rising = C.trendFor([sample(0, 50), sample(10, 49), sample(20, 48), sample(30, 47)]);
assert.equal(rising.direction, 'rising'); assert(Math.abs(rising.rate - 6) < 1e-9);
assert.equal(C.trendFor([sample(0, 47), sample(10, 48), sample(20, 49)]).direction, 'falling');
assert.equal(C.trendFor([sample(0, 50), sample(10, 50), sample(20, 50)]).direction, 'stable');
assert.equal(C.trendFor([sample(0, 50), sample(1, 49), sample(2, 48)]), null);
assert.equal(C.trendFor([sample(0, 50), sample(0, 49), sample(0, 48)]), null);
assert.equal(C.trendFor([sample(10, 50), sample(20, 49), sample(0, 48)]), null, 'RTC jumps backwards must not create a false slope');
assert.equal(C.trendFor([sample(0, 50), sample(10, 49), sample(20, 0)]), null);
assert.equal(C.trendFor([]), null);
assert.deepEqual(C.parsePause('PAUSED 1 REMAIN 300000'), { paused: true, remainingMs: 300000 });
assert.deepEqual(C.parsePause('@STATE PAUSED 0 REMAIN 0'), { paused: false, remainingMs: 0 });
assert.equal(C.parsePause('PAUSED 0 REMAIN 3000'), null);
assert.equal(C.parsePause('PAUSED 1 REMAIN 86400001'), null);
assert.equal(C.parsePause('PAUSED 1 REMAIN -2'), null);
const heartbeat = '@HEALTH UPTIME 10000 SENSOR OK AGE 50 CPIN 1 CSQ 19 CREG 0 CEREG 1 MODEMAGE 500 RTC 1 PAUSED 0 REMAIN 0';
assert.equal(C.parseHealth(heartbeat).rssi, 19);
assert.equal(C.parseHealth(heartbeat).cereg, 1);
assert.equal(C.parseHealth(heartbeat.replace('SENSOR OK', 'SENSOR NO_ECHO')).sensor, 'NO_ECHO');
assert.equal(C.parseHealth(heartbeat.replace('CSQ 19', 'CSQ 99')).rssi, 99);
assert.equal(C.parseHealth(heartbeat.replace('CSQ 19', 'CSQ 40')), null);
assert.equal(C.parseHealth(heartbeat.replace('RTC 1', 'RTC 2')), null);
assert.equal(C.parseHealth(heartbeat.replace('AGE 50', 'AGE -2')), null);
assert.equal(C.parseHealth(heartbeat.replace('RTC 1 ', '')), null);
assert.equal(C.parseHealth(heartbeat.replace('RTC 1', 'CSQ 19')), null);
assert.equal(C.parseHealth('arbitrary log'), null);
console.log('PASS: calibration/invalid ranges, independent cadences, legacy draft migration, rising/falling/stable slope, insufficient data/RTC reset, timed pause validation, complete health frames and unknown signal.');
